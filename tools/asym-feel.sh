#!/system/bin/sh
# 左右不等震动的体感验证（需要手柄连着）。
#
# 直接调 bridge.sh --once <左> <右> <ms> —— 绕过框架，但走的是和正式转发**同一条**
# send_report 路径，所以能验证「手柄到底认不认左右不等」。
#
# 用法：sh asym-feel.sh
# 每次 3 秒，间隔 8 秒，顺序如下（请留意是左边震、右边震、还是两边）：
#   ① 左=255 右=255   → 应该两边都震（基准）
#   ② 左=255 右=0     → 应该只有左边震
#   ③ 左=0   右=255   → 应该只有右边震
#   ④ 左=255 右=64    → 应该左边明显强、右边弱
M=/data/adb/modules/tb378fc_gamepad_rumble

cd "$M" || exit 1

echo "=== 先确认手柄在 ==="
node=$(sh bridge.sh --discover 2>/dev/null | head -1 | awk '{print $2}')
if [ -z "$node" ]; then
    echo "  ✗ 没找到手柄（/dev/hidraw* 为空）—— 先把手柄连上再跑"
    exit 1
fi
echo "  手柄节点: $node"

pulse() {  # $1=左 $2=右 $3=说明
    echo ""
    echo "  ┌──────────────────────────────────────────────────────"
    printf "  │ %s\n" "$3"
    printf "  │ 左=%-3s 右=%-3s   发出时间 %s\n" "$1" "$2" "$(date '+%H:%M:%S')"
    echo "  └──────────────────────────────────────────────────────"
    sh bridge.sh --once "$1" "$2" 3000 2>&1 | sed 's/^/     /'
}

pulse 255 255 "① 基准：两边都应该震"
sleep 8
pulse 255 0   "② 只有左马达（右=0）"
sleep 8
pulse 0   255 "③ 只有右马达（左=0）"
sleep 8
pulse 255 64  "④ 左强右弱（左=255 右=64）"

echo ""
echo "=== 请对照报告：哪几次震了、震的是哪一边 ==="
echo "  ① 两边 / ② 只有左 / ③ 只有右 / ④ 左强右弱 —— 是否符合？"
echo "  如果 ②③ 分不出左右（两次感觉一样），说明手柄只把 [4]/[5] 当"总强度"用了，"
echo "  那左右不等在本机就做不到（是手柄固件/描述符的限制，不是模块的问题）。"
